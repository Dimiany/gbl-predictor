function publicHelp() {
  return [
    pageBanner('Οδηγίες', 'Πώς να διαβάσεις το site.'),
    h('section', {class: 'panel howto'}, sectionHead('Ενημέρωση'),
      h('p', null, 'Το site ενημερώνεται αυτόματα: τα αποτελέσματα μπαίνουν το ίδιο βράδυ, και οι προβλέψεις της επόμενης αγωνιστικής καταγράφονται πριν από το τζάμπολ. Η τελευταία ενημέρωση φαίνεται στο κάτω μέρος κάθε σελίδας.')),
    siteGuide(),
  ];
}

